#!/usr/bin/env python3
"""Synchronize thin Codex adapters; source workflows stay under .claude/skills."""

import argparse
from pathlib import Path
import re
import sys


MARKER = "<!-- Generated by .claude/scripts/codex-skills.py; do not edit. -->"


def render(source):
    text = source.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or lines[0] != "---" or "---" not in lines[1:]:
        raise ValueError(f"Missing frontmatter: {source}")
    frontmatter = lines[1:lines.index("---", 1)]
    name = source.parent.name
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name) or len(name) > 56:
        raise ValueError(f"Invalid skill directory name: {name}")
    if f"name: {name}" not in frontmatter:
        raise ValueError(f"Source name does not match directory: {source}")
    descriptions = [line for line in frontmatter if line.startswith("description:")]
    if len(descriptions) != 1 or descriptions[0].split(":", 1)[1].strip() in (
        "", ">", "|", ">-", "|-", ">+", "|+",
    ):
        raise ValueError(f"Expected one single-line description: {source}")
    # Preserve the source YAML scalar verbatim, including its quoting/escaping.
    return f"""---
name: studio-{name}
{descriptions[0]}
---

{MARKER}

Follow this studio workflow in Codex:

1. Read root `AGENTS.md` and `docs/codex.md` for shared policy and runtime
   translations. All paths here are relative to the repository root.
2. Read `.claude/skills/{name}/SKILL.md` as the authoritative workflow.
   Its resources resolve from `.claude/skills/{name}/`, not this adapter.
3. Bind the arguments after `$studio-{name}` to the source workflow's
   argument syntax. Follow its phases and read references only when needed.
4. Explicitly run relevant preprocessing commands; Claude has not expanded
   variables, executed shell injections or loaded nested skills for you.

Preserve the source workflow's read-only boundaries and required decisions.
Root authorization and E2E-first testing policy overrides legacy conflicting
instructions. Report unavailable capabilities instead of inventing results.
"""


def synchronize(root, destination, check):
    sources = sorted((root / ".claude/skills").glob("*/SKILL.md"))
    if not sources:
        raise ValueError(f"No source skills under {root / '.claude/skills'}")
    expected = {f"studio-{source.parent.name}": render(source) for source in sources}
    actions = []
    for name, content in expected.items():
        path = destination / name / "SKILL.md"
        if path.parent.is_symlink() or path.is_symlink():
            raise ValueError(f"Refusing symlink adapter: {path}")
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing is not None and MARKER not in existing:
            raise ValueError(f"Refusing to overwrite an unmanaged skill: {path}")
        if existing != content:
            actions.append(("missing" if existing is None else "stale", path, content))
    for path in sorted(destination.glob("*/SKILL.md")):
        if path.parent.name not in expected and MARKER in path.read_text(encoding="utf-8"):
            if path.parent.is_symlink() or path.is_symlink():
                raise ValueError(f"Refusing symlink adapter: {path}")
            actions.append(("orphan", path, None))
    for reason, path, content in actions:
        print(f"{reason}: {path}")
        if not check:
            if content is None:
                path.unlink()
                if not any(path.parent.iterdir()):
                    path.parent.rmdir()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    print(f"{'Checked' if check else 'Synchronized'} {len(expected)} adapters; "
          f"{'drift' if check else 'changes'}={len(actions)}")
    return 1 if check and actions else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without writing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2],
                        help="Project root (defaults to the script's checkout)")
    parser.add_argument("--destination", type=Path,
                        help="Adapter directory (defaults to <root>/.agents/skills)")
    args = parser.parse_args()
    root = args.root.resolve()
    destination = args.destination or root / ".agents/skills"
    try:
        return synchronize(root, destination, args.check)
    except (OSError, ValueError) as error:
        print(f"codex-skills: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
